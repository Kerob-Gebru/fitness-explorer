// Define how Sequelize represents one row from the auth_sessions table.
// DataTypes describes each column, and the shared Sequelize instance connects
// this model to the configured database.
import { DataTypes } from "sequelize";
import sequelize from "../config/db.js";
import {
  AUTH_SESSION_COLUMNS,
  AUTH_SESSION_INDEXES,
  AUTH_SESSION_TABLE_METADATA,
  AUTH_SESSION_TABLE_NAME,
} from "./authSessionSchema.js";

// This model describes the existing auth_sessions table; it does not create or
// alter it. Attribute names match the existing snake_case column names.
const AuthSession = sequelize.define(
  "AuthSession",
  {
    // Session identifier generated by the application, not by the database.
    id: {
      type: DataTypes.CHAR(36),
      primaryKey: true,
      allowNull: false,
    },
    // Owner of the session; deleting the user deletes their sessions.
    user_id: {
      type: DataTypes.BIGINT.UNSIGNED,
      allowNull: false,
      references: { model: "users", key: "id" },
      onUpdate: "CASCADE",
      onDelete: "CASCADE",
    },
    // Only a hash of the refresh token is stored.
    refresh_token_hash: {
      type: DataTypes.CHAR(64),
      allowNull: false,
    },
    // The session becomes invalid after this time.
    expires_at: {
      type: DataTypes.DATE(3),
      allowNull: false,
    },
    // Set when the session is explicitly revoked; null means not revoked.
    revoked_at: {
      type: DataTypes.DATE(3),
      allowNull: true,
    },
    // Updated when the refresh token is used.
    last_used_at: {
      type: DataTypes.DATE(3),
      allowNull: true,
    },
    // Groups rotated refresh tokens so reuse can revoke the whole family.
    // Existing rows were backfilled by the migration; new sessions must supply
    // a value from the application because the column has no database default.
    token_family_id: {
      type: DataTypes.CHAR(36),
      allowNull: false,
    },
    // The session that superseded this one after rotation; null while current.
    replaced_by_session_id: {
      type: DataTypes.CHAR(36),
      allowNull: true,
      references: { model: "auth_sessions", key: "id" },
      onUpdate: "CASCADE",
      onDelete: "SET NULL",
    },
    created_at: {
      type: DataTypes.DATE(3),
      allowNull: false,
      defaultValue: DataTypes.NOW,
    },
    updated_at: {
      type: DataTypes.DATE(3),
      allowNull: false,
      defaultValue: DataTypes.NOW,
    },
  },
  {
    // Explicit mapping avoids Sequelize guessing a table name.
    tableName: AUTH_SESSION_TABLE_NAME,
    // Sequelize manages timestamps using the table's existing column names.
    timestamps: true,
    createdAt: "created_at",
    updatedAt: "updated_at",
    // Match the token, lookup, rotation-family, and replacement indexes.
    indexes: AUTH_SESSION_INDEXES.map((index) => ({ ...index })),
  }
);

export {
  AUTH_SESSION_TABLE_NAME,
  AUTH_SESSION_COLUMNS,
  AUTH_SESSION_INDEXES,
  AUTH_SESSION_TABLE_METADATA,
};

export default AuthSession;
