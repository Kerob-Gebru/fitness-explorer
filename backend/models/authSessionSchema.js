// Canonical schema descriptor for the `auth_sessions` database table.
// Shared between the Sequelize model (`AuthSession.js`), backend routes, and
// the local Express preview store so both environments enforce identical fields.

export const AUTH_SESSION_TABLE_NAME = "auth_sessions";

export const AUTH_SESSION_COLUMNS = Object.freeze({
  id: {
    type: "CHAR(36)",
    primaryKey: true,
    allowNull: false,
    description: "UUIDv4 session identifier generated by the server.",
  },
  user_id: {
    type: "BIGINT.UNSIGNED",
    allowNull: false,
    references: { table: "users", column: "id" },
    description: "Foreign key to the owning account in users.id.",
  },
  refresh_token_hash: {
    type: "CHAR(64)",
    allowNull: false,
    unique: true,
    description: "SHA-256 hex digest of the opaque refresh token.",
  },
  expires_at: {
    type: "DATE(3)",
    allowNull: false,
    description: "UTC timestamp when this session expires.",
  },
  revoked_at: {
    type: "DATE(3)",
    allowNull: true,
    description: "UTC timestamp when revoked or rotated; null while active.",
  },
  last_used_at: {
    type: "DATE(3)",
    allowNull: true,
    description: "UTC timestamp of the most recent refresh or login activity.",
  },
  token_family_id: {
    type: "CHAR(36)",
    allowNull: false,
    description: "UUIDv4 family identifier grouping rotated refresh tokens.",
  },
  replaced_by_session_id: {
    type: "CHAR(36)",
    allowNull: true,
    references: { table: "auth_sessions", column: "id" },
    description: "Self-FK pointing to the newer session after token rotation.",
  },
  created_at: {
    type: "DATE(3)",
    allowNull: false,
    description: "UTC creation timestamp.",
  },
  updated_at: {
    type: "DATE(3)",
    allowNull: false,
    description: "UTC last-modified timestamp.",
  },
});

export const AUTH_SESSION_INDEXES = Object.freeze([
  { name: "auth_sessions_refresh_token_unique", unique: true, fields: ["refresh_token_hash"] },
  { name: "auth_sessions_user_expiry", fields: ["user_id", "expires_at"] },
  { name: "auth_sessions_user_family_revoked", fields: ["user_id", "token_family_id", "revoked_at"] },
  { name: "auth_sessions_replaced_by_session", fields: ["replaced_by_session_id"] },
]);

export const AUTH_SESSION_TABLE_METADATA = Object.freeze({
  tableName: AUTH_SESSION_TABLE_NAME,
  columns: Object.entries(AUTH_SESSION_COLUMNS).map(([name, spec]) => ({
    name,
    type: spec.type,
    nullable: Boolean(spec.allowNull),
    primaryKey: Boolean(spec.primaryKey),
    unique: Boolean(spec.unique),
    references: spec.references || null,
    description: spec.description,
  })),
  indexes: AUTH_SESSION_INDEXES,
});

export function buildAuthSessionRow({
  id,
  user_id,
  refresh_token_hash,
  expires_at,
  revoked_at = null,
  last_used_at = null,
  token_family_id,
  replaced_by_session_id = null,
  now = new Date(),
}) {
  const isoNow = now instanceof Date ? now.toISOString() : String(now);
  const isoExpires = expires_at instanceof Date ? expires_at.toISOString() : String(expires_at);

  return {
    id: String(id),
    user_id: Number(user_id),
    refresh_token_hash: String(refresh_token_hash),
    expires_at: isoExpires,
    revoked_at: revoked_at ? new Date(revoked_at).toISOString() : null,
    last_used_at: last_used_at ? new Date(last_used_at).toISOString() : null,
    token_family_id: String(token_family_id),
    replaced_by_session_id: replaced_by_session_id ? String(replaced_by_session_id) : null,
    created_at: isoNow,
    updated_at: isoNow,
  };
}
